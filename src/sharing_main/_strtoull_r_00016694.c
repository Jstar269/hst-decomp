/*
 * Convert a string to an unsigned long long integer.
 *
 * Ignores `locale' stuff.  Assumes that the upper and lower case
 * alphabets and digits are each contiguous.
 */
unsigned long long
_strtoull_r(struct _reent *rptr , const char *nptr , char **endptr , int base)




{
        register const char *s = nptr;
        register unsigned long long acc;
        register int c;
        register unsigned long long cutoff;
        register int neg = 0, any, cutlim;

        /*
	 * See strtol for comments as to the logic used.
	 */
        do {
                c = *s++;
        } while (((_ctype_+1)[(unsigned)(c)]&010));
        if (c == '-') {
                neg = 1;
                c = *s++;
        } else if (c == '+')
                c = *s++;
        if ((base == 0 || base == 16) &&
            c == '0' && (*s == 'x' || *s == 'X')) {
                c = s[1];
                s += 2;
                base = 16;
        }
        if (base == 0)
                base = c == '0' ? 8 : 10;
        cutoff = (unsigned long long)18446744073709551615ULL / (unsigned long long)base;
        cutlim = (unsigned long long)18446744073709551615ULL % (unsigned long long)base;
        for (acc = 0, any = 0;; c = *s++) {
                if (((_ctype_+1)[(unsigned)(c)]&04))
                        c -= '0';
                else if (((_ctype_+1)[(unsigned)(c)]&(01|02)))
                        c -= ((_ctype_+1)[(unsigned)(c)]&01) ? 'A' - 10 : 'a' - 10;
                else
                        break;
                if (c >= base)
                        break;
               if (any < 0 || acc > cutoff || (acc == cutoff && c > cutlim))
                        any = -1;
                else {
                        any = 1;
                        acc *= base;
                        acc += c;
                }
        }
        if (any < 0) {
                acc = 18446744073709551615ULL;
                rptr->_errno = 34;
        } else if (neg)
                acc = -acc;
        if (endptr != 0)
                *endptr = (char *) (any ? s - 1 : nptr);
        return (acc);
}
